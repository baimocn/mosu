# -*- coding: utf-8 -*-
"""常驻 —— 微信通道与 GUI 控制台共用。

首选通道：Windows 计划任务（登录即启动 + 崩溃自愈 2min×5 次 + 无时长限制）。
降级通道：某些机器被系统策略锁了「登录时启动」的计划任务（Register-ScheduledTask
对 AtLogOn 触发器报 0x80070005/拒绝访问，企业安全策略或优化软件常见）——
自动降级为「启动文件夹 + VBS 守护」：登录时起一个守护脚本，服务挂了 5 秒内拉起。

非 Windows 平台：明确提示改用 systemd / supervisor，不假装支持。
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _ps(cmd: str, timeout: int = 120):
    """跑 PowerShell。stdout 显式 utf-8 + errors=replace：
    Windows PowerShell 5.1 输出按 GBK 编码，Python 3.14 默认 UTF-8 严解码会
    UnicodeDecodeError 崩在读线程里（注册其实可能已成功，但拿不到 returncode）。
    """
    return subprocess.run(
        ["powershell", "-NoProfile", "-NonInteractive", "-Command", cmd],
        capture_output=True, text=True,
        encoding="utf-8", errors="replace", timeout=timeout)


def _startup_dir() -> Path:
    return Path(os.environ.get("APPDATA", "")) / \
        "Microsoft/Windows/Start Menu/Programs/Startup"


# ---------------------------------------------------------------- 首选：计划任务
def _install_scheduled(task_name: str, args: str) -> bool:
    py = sys.executable
    ps = (
        "$ErrorActionPreference='Stop';"
        f"$a=New-ScheduledTaskAction -Execute '{py}' "
        f"-Argument '-u cli/mosu.py {args}' -WorkingDirectory '{ROOT}';"
        "$t=New-ScheduledTaskTrigger -AtLogOn;"
        "$s=New-ScheduledTaskSettingsSet -RestartCount 5 "
        "-RestartInterval (New-TimeSpan -Minutes 2) -ExecutionTimeLimit 0 "
        "-StartWhenAvailable;"
        f"Register-ScheduledTask -TaskName '{task_name}' -Action $a -Trigger $t "
        "-Settings $s -Force | Out-Null;"
        f"Start-ScheduledTask -TaskName '{task_name}';"
        f"Write-Output 'OK {task_name}'"
    )
    try:
        r = _ps(ps)
        if r.returncode == 0:
            print(f"✅ 常驻任务已注册并启动：{task_name}（计划任务）")
            print("   · 登录即自动启动（不用手动开）")
            print("   · 崩溃后 2 分钟间隔自动重启，最多 5 次")
            print("   · 无执行时长限制（不会被系统掐断）")
            return True
        print(f"[!] 计划任务注册失败：{(r.stderr or r.stdout).strip()[:300]}")
        return False
    except Exception as e:
        print(f"[!] 计划任务注册异常：{type(e).__name__}: {e}")
        return False


# ---------------------------------------------------------------- 降级 1：schtasks 原生通道
def _install_schtasks(task_name: str, args: str) -> bool:
    """PowerShell 的 Register-ScheduledTask 在某些机器上被策略拒绝
    （AtLogOn 触发器报 0x80070005）。schtasks.exe 走的是另一条 API 路径，
    个别机器只堵 PowerShell 而不堵 schtasks，值得单独试一次。

    注意 MSYS/Git Bash 会把 /tr 这类参数当路径转换掉，直接拼命令行必坏；
    这里用 subprocess 传列表，绕开外壳。
    """
    py = sys.executable
    tr = f'"{py}" -u "{ROOT / "cli" / "mosu.py"}" {args} --no-browser'
    cmd = ["schtasks", "/create", "/tn", task_name, "/tr", tr,
           "/sc", "onlogon", "/f"]
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=120)
    except Exception as e:
        print(f"[!] schtasks 注册异常：{type(e).__name__}: {e}")
        return False

    def _text() -> str:
        # 中文 Windows 的 schtasks 输出是 GBK；utf-8 严解码会把错误信息
        # 变成乱码，导致「拒绝访问」识别失效
        for enc in ("gbk", "utf-8"):
            try:
                return (r.stdout or b"").decode(enc) + (r.stderr or b"").decode(enc)
            except UnicodeDecodeError:
                continue
        return (r.stdout or b"").decode("utf-8", "replace")

    if r.returncode == 0:
        print(f"✅ 常驻任务已注册：{task_name}（schtasks 登录触发）")
        print("   · 登录即自动启动")
        print("   · 用 schtasks 查询/管理：schtasks /query /tn " + task_name)
        return True
    detail = _text().strip()
    if "拒绝访问" in detail or "Access is denied" in detail:
        print("[!] schtasks 也被本机策略拒绝（登录触发器受限）")
    else:
        print(f"[!] schtasks 注册失败：{detail[:200]}")
    return False


# ---------------------------------------------------------------- 降级 2：启动文件夹
def _install_startup(task_name: str, args: str) -> int:
    """启动文件夹 + VBS 守护。VBS 按系统 ANSI（中文 Windows = GBK）读写，
    文件用 GBK 编码写，避免中文路径乱码。"""
    sd = _startup_dir()
    if not sd.parent.exists():
        print(f"[x] 找不到启动文件夹：{sd.parent}")
        print("   非 Windows 请用 systemd / supervisor 守护")
        return 1
    sd.mkdir(parents=True, exist_ok=True)
    vbs = sd / f"{task_name}.vbs"
    py = sys.executable
    # VBS 字符串拼接用 Chr(34) 表示引号——避免 Python f-string 与 VBS 的
    # """" 转义序列相撞（连续四个引号会提前终止 Python 三引号字符串）
    body = f"""' mosu resident guard (auto-generated by `mosu {args.split()[0]} install`)
' Keeps the service alive: if it exits, relaunch after 5 seconds.
Set sh = CreateObject("WScript.Shell")
q = Chr(34)
py = "{py}"
root = "{ROOT}"
cmd = q & py & q & " -u " & q & root & "\\cli\\mosu.py" & q & " {args} --no-browser"
Do While True
    sh.Run cmd, 0, True
    WScript.Sleep 5000
Loop
"""
    try:
        vbs.write_text(body, encoding="gbk")
    except Exception as e:
        print(f"[x] 写守护脚本失败：{type(e).__name__}: {e}")
        return 1
    print(f"✅ 常驻已注册：{task_name}（启动文件夹 + 守护脚本）")
    print(f"   脚本：{vbs}")
    print("   · 登录即自动启动，服务退出后 5 秒内自动拉起")
    print("   · 计划任务的 AtLogOn 触发器被本机策略禁止，已自动降级到此通道")
    print("   · 卸载：mosu gui uninstall / mosu wechat uninstall")
    return 0


# ---------------------------------------------------------------- 对外三件套
def install_task(task_name: str, args: str) -> int:
    if _install_scheduled(task_name, args):
        return 0
    print("[i] 计划任务通道不可用，试 schtasks 原生通道…")
    if _install_schtasks(task_name, args):
        return 0
    print("[i] 降级到「启动文件夹 + VBS 守护」通道…")
    return _install_startup(task_name, args)


def uninstall_task(task_name: str) -> int:
    ok = False
    # 通道 1：计划任务
    try:
        r = _ps(f"Stop-ScheduledTask -TaskName '{task_name}' -ErrorAction SilentlyContinue;"
                f"Unregister-ScheduledTask -TaskName '{task_name}' -Confirm:$false;"
                f"Write-Output 'removed {task_name}'")
        if r.returncode == 0 and "removed" in (r.stdout or ""):
            print(f"✅ 已卸载计划任务 {task_name}")
            ok = True
    except Exception:
        pass
    # 通道 2：schtasks 注册的任务
    try:
        r = subprocess.run(["schtasks", "/delete", "/tn", task_name, "/f"],
                           capture_output=True, timeout=120)
        if r.returncode == 0:
            print(f"✅ 已卸载计划任务 {task_name}（schtasks）")
            ok = True
    except Exception:
        pass
    # 通道 3：启动文件夹守护脚本
    vbs = _startup_dir() / f"{task_name}.vbs"
    if vbs.exists():
        try:
            vbs.unlink()
            print(f"✅ 已删除守护脚本 {vbs}")
            ok = True
        except Exception as e:
            print(f"[x] 删守护脚本失败：{type(e).__name__}: {e}")
    if not ok:
        print(f"[i] 没找到常驻任务 {task_name}（可能本来就没装）")
    print("[i] 正在运行的服务若由计划任务拉起，会随之停止；可随时用桌面快捷方式重启")
    return 0


def task_status(task_name: str) -> int:
    found = False
    # 通道 1
    try:
        r = _ps(f"Get-ScheduledTask -TaskName '{task_name}' -ErrorAction SilentlyContinue | "
                "Select-Object TaskName,State | Format-Table -AutoSize | Out-String;"
                f"Get-ScheduledTaskInfo -TaskName '{task_name}' -ErrorAction SilentlyContinue | "
                "Select-Object LastRunTime,LastTaskResult,NextRunTime | "
                "Format-List | Out-String")
        out = (r.stdout or "").strip()
        if out:
            print(f"[计划任务] {task_name}")
            print(out)
            found = True
    except Exception as e:
        print(f"[!] 查询计划任务失败：{type(e).__name__}: {e}")
    # 通道 2
    vbs = _startup_dir() / f"{task_name}.vbs"
    if vbs.exists():
        print(f"[启动文件夹] {vbs}（守护脚本在，登录自启）")
        found = True
    if not found:
        print(f"未找到常驻任务 {task_name}（运行 mosu gui install / mosu wechat install 安装）")
    return 0
